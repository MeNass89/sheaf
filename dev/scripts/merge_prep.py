#!/usr/bin/env python3
"""Phase 4 glue. Run from the project root.

  merge_prep.py features   dev/board/raw/*.json → dev/board/features.json (one list, stable order)
                           and dev/.tmp/merge/<domain>.json (rows of one domain with their global index)
  merge_prep.py build      dev/.tmp/merge/<domain>.groups.json (agents' groupings) → dev/board/components.json
                           (keeps the decisions already written in an existing components.json)
"""
import glob, json, pathlib, sys

RAW = sorted(glob.glob("dev/board/raw/*.json"))
FEATS = pathlib.Path("dev/board/features.json")
OURS = pathlib.Path("dev/board/ours.json")
COMPS = pathlib.Path("dev/board/components.json")
TMP = pathlib.Path("dev/.tmp/merge")

# Sheaf's own inventory areas → board domains.
OURS_DOMAIN = {
    "Home & files": "files", "Tools grid": "files", "History & recents": "output", "Results & saving": "output",
    "Edit": "edit", "Organize pages": "organize", "Convert from PDF": "convert", "Convert to PDF": "convert",
    "Optimize": "optimize", "Viewer": "reader", "Sign": "sign", "Redact": "security", "Security": "security",
    "Compare": "compare", "Preferences": "preferences", "Platform": "platform", "CLI": "platform", "MCP": "platform",
}


def features():
    rows = []
    for f in RAW:
        rows += json.load(open(f))
    FEATS.write_text(json.dumps(rows, ensure_ascii=False, indent=1) + "\n")
    TMP.mkdir(parents=True, exist_ok=True)
    by = {}
    for i, r in enumerate(rows):
        by.setdefault(r["domain"], []).append({"i": i, "app": r["app"], "area": r.get("area", ""), "feature": r["feature"], "behavior": r.get("behavior", "")[:220]})
    ours = json.load(open(OURS))
    for j, r in enumerate(ours):
        d = OURS_DOMAIN.get(r["area"], "platform")
        by.setdefault(d, []).append({"o": j, "app": "sheaf", "area": r["area"], "feature": r["feature"], "behavior": r.get("behavior", "")[:220], "limits": r.get("limits", "")})
    for d, v in by.items():
        (TMP / f"{d}.json").write_text(json.dumps(v, ensure_ascii=False, indent=0))
    print(len(rows), "rows;", {d: len(v) for d, v in sorted(by.items())})


def build():
    rows = json.load(open(FEATS))
    old = {c["id"]: c for c in json.load(open(COMPS))} if COMPS.exists() else {}
    comps = []
    for g in sorted(TMP.glob("*.groups.json")):
        for c in json.load(open(g)):
            apps = {}
            for i in c["rows"]:
                a = rows[i]["app"]
                x = apps.setdefault(a, {"has": "yes", "how": "", "code": [], "source": rows[i].get("source", "code")})
                if not x["how"]:
                    x["how"] = rows[i].get("behavior", "")[:300]
            comp = {"id": c["id"], "name": c["name"], "domain": c["domain"], "definition": c["definition"],
                    "weight": c.get("weight", "normal"), "main": None, "main_why": "", "apps": apps, "take": {},
                    "unique": len(apps) == 1, "rows": c["rows"], "ours": c.get("ours", []),
                    "grade": {}, "status": "open", "feature": None, "next": "", "history": []}
            prev = old.get(c["id"])
            if prev:   # keep decisions and located code
                for k in ("main", "main_why", "take", "weight", "grade", "status", "feature", "next", "history"):
                    comp[k] = prev.get(k, comp[k])
                for a, x in prev.get("apps", {}).items():
                    if a in comp["apps"]:
                        comp["apps"][a]["code"] = x.get("code", [])
                        comp["apps"][a]["source"] = x.get("source", comp["apps"][a]["source"])
                        comp["apps"][a]["how"] = x.get("how") or comp["apps"][a]["how"]
            comps.append(comp)
    COMPS.write_text(json.dumps(comps, ensure_ascii=False, indent=1) + "\n")
    print(len(comps), "components")


AX = ("function", "aesthetics", "performance")
DEC = pathlib.Path("dev/board/decisions")
LOG = pathlib.Path("dev/DECISIONS.md")
BEGIN, END = "<!-- board decisions: generated by merge_prep.py decide -->", "<!-- end board decisions -->"


def decide():
    """dev/board/decisions/<domain>.py (D = {"NNN": (main, why, take, (F, A, P), next)}) → components.json,
    and the per-component decision table in DECISIONS.md."""
    comps = json.load(open(COMPS))
    by = {c["id"]: c for c in comps}
    lines, bad = [BEGIN, ""], 0
    for f in sorted(DEC.glob("*.py")):
        dom = f.stem
        ns = {}
        exec(f.read_text(), ns)
        lines += [f"### Board · {dom} (2026-10-20)", "", "| id | component | weight | main | why | take | Sheaf F·A·P |", "|---|---|---|---|---|---|---|"]
        for n, (main, why, take, g, nxt) in ns["D"].items():
            c = by.get(f"C-{dom}-{n}")
            if not c:
                print("no component", dom, n); bad += 1; continue
            if main not in c["apps"] and main != "ours":
                print(f"{c['id']}: main {main} not among {list(c['apps'])}"); bad += 1
            c["main"], c["main_why"], c["take"], c["next"] = main, why, take, nxt
            c["grade"] = dict(zip(AX, g)); c["grade"]["overall"] = min(g)
            if not c.get("history"):
                c["history"] = [{"date": "2026-10-20", "feature": None, "grade": dict(c["grade"]), "proof": "phase 4 baseline: dev/board/ours.json rows " + str(c.get("ours", []))}]
            t = "; ".join(f"{a}: {s}" for a, s in take.items())
            lines.append(f"| {c['id']} | {c['name']} | {c['weight']} | {main} | {why} | {t} | {g[0]}·{g[1]}·{g[2]} |".replace("\n", " "))
        lines.append("")
        missing = [c["id"] for c in comps if c["domain"] == dom and c["id"].split("-")[-1] not in ns["D"]]
        if missing:
            print("undecided:", missing); bad += len(missing)
    lines.append(END)
    COMPS.write_text(json.dumps(comps, ensure_ascii=False, indent=1) + "\n")
    log = LOG.read_text()
    block = "\n".join(lines)
    log = log.split(BEGIN)[0].rstrip() + "\n\n" + block + log.split(END)[1] if BEGIN in log else log.rstrip() + "\n\n" + block + "\n"
    LOG.write_text(log)
    print(f"decided; {bad} problem(s)")


def fix():
    """After locate.py: say plainly where no code was found, and give Sheaf-only components their 'no' rows."""
    comps = json.load(open(COMPS))
    n = 0
    for c in comps:
        if not c["apps"]:
            c["apps"] = {"acrobat": {"has": "no", "how": "no equivalent in any inspiration's extracted features", "code": [], "source": "none"}}
            n += 1
        for a, x in c["apps"].items():
            if x.get("has") in ("yes", "partial") and not x.get("code") and x.get("source") not in ("docs", "ui", "none"):
                x["source"] = "none"
                x["how"] = (x.get("how") or "") + " [locate.py: no literal hit for the evidence strings]"
                n += 1
    COMPS.write_text(json.dumps(comps, ensure_ascii=False, indent=1) + "\n")
    print(n, "fixed")


if __name__ == "__main__":
    {"features": features, "build": build, "decide": decide, "fix": fix}[sys.argv[1]]()
